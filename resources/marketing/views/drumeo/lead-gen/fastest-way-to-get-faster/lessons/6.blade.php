        Sometimes you’ll hear a drummer playing a beat that sounds extremely difficult and fast, but when you break it down it’s actually shocking in its simplicity. This actually happens to me quite a bit when I read song transcriptions for what my favorite drummers played for famous songs.
        <br><br> Today’s set of exercises is all about playing things that sound crazy fast, but can be very simple when you add your feet! You can play this starting with the bass drum or hands - it’s up to you. Just make sure to alternate hands to really test your balance and speed.
        <br><br> Start off just practicing the first exercise a lot before moving on. It’s likely that the next two will be much easier once you get the basic feel for the pattern. Just keep an eye on the later two: they look similar but the hand patterns change to double strokes and a single paradiddle. I’m sure you’ll get the idea.
