    <p class="text-left hide">
        Sequels are never as good as the original, right? Well we’re going to break that trend with the second part of “Do You Even Math”. Today we’re going to challenge your abilities as we play groupings of 3, 5, and 7 between the hands and feet.
        <br><br> For the first exercise, we’re playing groups of 3 using 16th note triplets. The right and left hands will alternate as you place the kicks in between. As an added challenge, you can also play quarter notes with your hi-hat foot. Once you have nailed the basic pattern, feel free to start moving it around the drums, this works great in solos.
        <br><br> The next exercise is also played as 16th note triplets, but we’re going to use groups of 5. I have become obsessed with using RLRLL as a hand pattern (thanks to Benny Greb), so in this case I split it up between the hands and feet. What would normally be the left hand is now going to be played on the bass drum and we’re going to split to the two main hand strokes between the right and left hand. Take your time with this one and make sure you practice using a metronome so you know you’re playing it in time using the correct note value.
        <br><br> The final exercise is the same concept as previous, but this time we’re going to play sevens. Similarly to playing fives as RLRLL, we’re going to play sevens as RLRLRLL but place the main foot where our left hand, and alternate the hits on the hands. You’ll notice that the hand lead patterns actually change each time the sequence repeats. The first exercise is written in 4/4, the next one is 5/4, and the last one is 7/4. I’ve done this so they all naturally repeat and it creates a nice sequence of exercises for practicing.
        <br><br> Start practicing all of these at 50-60 bpm and speed them up in 5 bpm increments as you get comfortable with the patterns.
