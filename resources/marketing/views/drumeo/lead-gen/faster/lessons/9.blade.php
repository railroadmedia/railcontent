        Yes, I stole the title. It’s actually a line from the Tegan and Sara song “Everything Is Awesome” which is part of the soundtrack to The LEGO Movie. It’s burned into my memory from hearing my kids running around the house screaming it.
        <br><br> Anyways, these next two exercises are fun ones. After studying lots of technique over the years (thanks Dom Famularo, Claus Hessler, Mike Michalkow, Lionel Duperron, and my many other great teachers), I’ve always wondered how drummers will go from 0-100 mph with their sticks using hardly any effort. As I studied more, I found that this is simply a technique issue.
        <br><br> What I’ve done to practice this myself is played my hands in unison. This helped me determine if there are any weak points with my hands. Most of you will find that your weak hand is much slower and less controlled. Since you’re only as fast as your weakest limb, you need to make sure you start at your weak hand’s slowest tempo.
        <br><br> The first exercise has two beats of the hands played unison with the kick drum stroke on the “let”, then we split the hands up and play 16th note triplets for the second half of the exercise. Technically, the hands aren’t actually playing any faster individually, but when they’re off-set instead of played unison it sounds quite fast! When I practice this I simply throw my sticks down at slightly different times, using the rebound of the stick which is controlled by the fingers, to keep the note spacing even. This can take time to learn but it’s so worth it!
        <br><br> The second exercise is similar, but this time we’re playing longer groups of unison and single strokes. You can continue to expand on this if you like, playing groups of 8, 10, or even 12 notes. I’d recommend starting very slowly at around 60 bpm and then speed it up from there.
