@section('lesson-description')
    <p>
        Welcome to Sight-Reading Made Simple - A Beginner's Guide To Reading Music! In this series, you’ll learn how the notes on the piano are represented on a musical score. Even better, you’ll get some great tips and techniques to read music on a score quickly, so you can play music you may not have seen before.
        <br><br> I often say learning to sight-read music is like learning to read a foreign language while riding a bike and juggling. It’s NO SMALL TASK! But it can be done, and in this series, I am going to take you through step-by-step the best way to learn how to read music, without the confusion.
        <br><br> Now, you might already know some of the concepts I’m about to explain. If you do, that’s awesome! Feel free to skip ahead. But before we can learn what the notes are on a page, we need to know what they are on the keyboard.
    </p>

    <div class="text-3xl mt-5 mb-2"><strong>Naming the notes</strong></div>

    <p class="mb-4">
        Every key on the keyboard has a letter name attached to it. That letter is from the musical alphabet, which goes from A-G. Like this:
    </p>

    <img class="mb-4" src="https://d2vyvo0tyx8ig5.cloudfront.net/sight-reading-made-simple/assets/1-keyboard-notes-A-G-1.png" alt="keyboard-notes-A-G-1">

    <p>
        When you get to G, you head back to A and repeat it all over again.
    </p>

    <div class="text-3xl mt-5 mb-2"><strong>Your fingers are numbered</strong></div>

    <p class="mb-4">
        Your fingers have numbers. Each finger (and thumb) has a different number. As you can see below, your thumbs are number 1 and your pinkies are number 5:

    </p>

    <img class="mb-4" src="https://d2vyvo0tyx8ig5.cloudfront.net/sight-reading-made-simple/assets/1-finger-numbers-1.png" alt="finger-numbers">

    <p>
        Our ‘home base’ on the piano for this lesson will be Middle C. Middle C is the C note that is located nearest to the middle of your piano. (It’s not actually the middle note of the piano, but it is pretty close!)
        <br><br> We’ll start by putting our right-hand thumb (or number 1 finger) on Middle C. Your left-hand pinky (number 5) goes on the C BELOW Middle C. We call that Low C. This position is called C Position.
        <br><br> To warm up, try playing the five notes that lie under your fingers up and down a few times.
    </p>

    <div class="text-3xl mt-5 mb-2"><strong>Let’s talk about rhythm</strong></div>

    <p class="mb-4">
        We can’t learn how to read music without first understanding rhythm! Notated music is shown in rhythmic groupings. On a piece of music you will see vertical lines. These are called bar lines. The space between the lines is called a bar, or measure:
    </p>

    <img class="mb-4" src="https://d2vyvo0tyx8ig5.cloudfront.net/sight-reading-made-simple/assets/ZZ-blank-staff-1.png" alt="ZZ-blank-staff">

    <p class="mb-4">
        Inside each bar, we have a certain number of notes. So how do we know how many notes we can fit inside each bar? Well, that’s the job of the Time Signature:
    </p>

    <img class="mb-4" src="https://d2vyvo0tyx8ig5.cloudfront.net/sight-reading-made-simple/assets/trebleclef-time-signature-1.png" alt="trebleclef-time-signature">

    <p class="mb-4">
        The Time Signature is what tells us how many beats each bar gets. The time signature above is called Four-Four. It means that we can have four beats in each bar, and each beat = 1 quarter note.
        <br><br> This is a quarter note:
    </p>

    <img class="mb-4" src="https://d2vyvo0tyx8ig5.cloudfront.net/sight-reading-made-simple/assets/zz-quarter-note-1.png" alt="zz-quarter-note">

    <p class="mb-4">
        It equals one beat. So we can fit four of these inside our bar.
        <br><br> There are other notes as well. This is a half note:
    </p>

    <img class="mb-4" src="https://d2vyvo0tyx8ig5.cloudfront.net/sight-reading-made-simple/assets/zz-half-note-1.png" alt="zz-half-note">

    <p class="mb-4">A half note equals two beats. It is twice as long as a quarter note. So we could fit two half notes in our bar next to the quarter notes, like this:</p>

    <img class="mb-4" src="https://d2vyvo0tyx8ig5.cloudfront.net/sight-reading-made-simple/assets/3h-quarter-notes-half-notes-numbers-nocount-1.png" alt="3h-quarter-notes-half-notes-numbers-nocount">

    <p class="mb-4">
        If we have a half note, that means we can have a whole note, right? Correct! This is a whole note:
    </p>

    <img class="mb-4" src="https://d2vyvo0tyx8ig5.cloudfront.net/sight-reading-made-simple/assets/zz-whole-note-1.png" alt="zz-whole-note">

    <p class="mb-4">
        A whole note is twice as long as a half note, and four times as long as a quarter note. So it takes up the whole of our bar.
        <br><br> There is one more note we are going to learn, and it’s my personal favorite. It’s called an eighth note, and it looks like this:
    </p>

    <img class="mb-4" src="https://d2vyvo0tyx8ig5.cloudfront.net/sight-reading-made-simple/assets/zz-eighth-note-1.png" alt="zz-eighth-note">

    <p class="mb-4">
        You might be able to guess how long an eighth note is. It is half the length of a quarter note. You can fit eight eighth notes in one bar. Make sense?
        <br><br> As you can see eighth notes have a little flag coming off their stem. That’s when they are on their own. When they are next to each other, they hold hands and connect, like a little bridge: Eighth notes are often grouped in two’s because two eighth notes equal 1 beat.
    </p>

    <img class="mb-4" src="https://d2vyvo0tyx8ig5.cloudfront.net/sight-reading-made-simple/assets/zz-eighth-notes-1.png" alt="zz-eighth-notes">

    <p>And that is your introduction to rhythm! Make sure you watch the lesson to practice along at the piano. In our next lesson, we are going to look at the musical staff and move the notes from the keys to the page.</p>

