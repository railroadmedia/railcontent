    <p class="mb-4">
        Now that’s a lot to remember! Fortunately, there are some easy ways to remember the note names. To do this, it can be helpful to think of an easy-to-remember phrase. For example, the lines on the treble staff represent the notes E, G, B, D, and F. To remember this, teachers often use the phrase: Every Good Boy Deserves Fudge. It’s a silly phrase, but it’s easy to remember and that’s the whole point.
        <br><br> You can also use the phrase: Every Good Boy Does Fine. It’s really up to you for whatever is easiest to remember!
    </p>

    <img class="mb-4" src="https://d2vyvo0tyx8ig5.cloudfront.net/sight-reading-made-simple/assets/trebleclef-egbdf-1.png" alt="trebleclef-egbdf">

    <p class="mb-4">
        Remembering the spaces is even easier! From the bottom, the notes are F, A, C, and E. They spell the word FACE!
    </p>

    <img class="mb-4" src="https://d2vyvo0tyx8ig5.cloudfront.net/sight-reading-made-simple/assets/trebleclef-face-1.png" alt="trebleclef-face">

    <p>
        As you can see, the order of the notes on the staff is the same as the order of the notes of the actual keys on the piano. So F comes after E, and before G etc.
    </p>

    <div class="text-3xl mt-5 mb-2">
        <strong>Middle C: A Line Of Its Own</strong>
    </div>

    <p class="mb-4">
        So where is Middle C in all this? Remember Middle C is our ‘home base’. Well, Middle C is actually BELOW the staff, on a separate little line all of its own. We’ll talk about why that is later in the series, but for now, you just need to know that’s where it is:
    </p>

    <img class="mb-4" src="https://d2vyvo0tyx8ig5.cloudfront.net/sight-reading-made-simple/assets/trebleclef-middle-c-1.png" alt="trebleclef-middle-c">

    <p class="mb-4">
        So if that is C, then the space above the Middle C line but below the E line would be D! So going up from C we have C, D, E, F, G, A, B, C, D, E, and F on the top line. And that’s as far as we will go:
    </p>

    <img class="mb-4" src="https://d2vyvo0tyx8ig5.cloudfront.net/sight-reading-made-simple/assets/trebleclef-all-notes-1.png" alt="trebleclef-all-notes">

    <div class="text-3xl mt-5 mb-2">
        <strong>Speeding It up</strong>
    </div>

    <p class="mb-4">
        So now we know what all the notes are, how do we get better at reading them quickly? We don’t want to stop at each note to figure out which one it is!
        <br><br> I find the easiest way to read notes, especially if you are reading them for the first time, is to combine knowing a few ‘landmark’ notes and then looking for patterns in the music.
        <br><br> For example. We know that notes that go from a line to a space, or from a space to a line are just one step apart. This means if we have Middle C, which is a line and D, which is a space, we can READ the C and the look at the next note and know it’s a D based on how far away it is from the C. If that pattern continues from line to space to line, we know we are just stepping up one note at a time:
    </p>

    <img class="mb-4" src="https://d2vyvo0tyx8ig5.cloudfront.net/sight-reading-made-simple/assets/trebleclef-staff-eighth-notes-1.png" alt="trebleclef-staff-eighth-notes">

    <p class="mb-4">
        The more you practice and play, the more you will remember and get comfortable with all the notes on the staff, but this is a great way to increase the speed of your reading as you practice.
        <br><br> We can also use the same logic for what I like to call jumps (or skips). That’s where you have a line note going to the next line note. Or a space going to the next space. It’s jumping or skipping over the line or space in between.
        <br><br> So let’s start on Middle C again. We know this is C, as it is our landmark note. Just from that, we can tell that the next line up will be E, because it is two steps away from C on the keyboard. And the next line is G, which is two steps up from E.
    </p>

    <img class="mb-4" src="https://d2vyvo0tyx8ig5.cloudfront.net/sight-reading-made-simple/assets/trebleclef-staff-half-notes-1.png" alt="trebleclef-staff-half-notes">

    <p>
        This technique is really useful when we are playing phrases of music we haven’t seen before. To put it into practice, we only really need to know the first note of the phrase, and we can look at the pattern to figure out the rest really quickly!
