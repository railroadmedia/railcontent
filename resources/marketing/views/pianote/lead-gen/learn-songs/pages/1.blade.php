    <p>The great thing about the piano is that the note names simply repeat up and down the keyboard. So you start with A and work your way up to G. Once you get to G, you simply start over again.
        <br><br> Finding and remembering all the names of the notes can be tricky, so it’s helpful to identify some “Landmark” notes. These are notes that you can use to quickly find your spot on the keyboard.
        <br><br> The first is the most common: C
        <br><br> To find C, simply find a group of 2 black keys on the piano. The white note immediately to the left of that group of 2 is C.
    </p>

    <video class="rounded-xl my-7" src="https://d2vyvo0tyx8ig5.cloudfront.net/lead-gen/learn-3-songs/lessons/finding-c.mp4" autoplay muted playsinline loop></video>

    <p>The next landmark note to learn is F. To find F, simply look for a group of 3 black keys anywhere on the piano. The white note immediately to the left of that group of 3 is F.
        <br><br> Once you get comfortable finding C and F, it becomes a lot easier to move to any other note on the piano.
        <br><br> So your homework is to spend some time familiarizing yourself with the musical alphabet.
