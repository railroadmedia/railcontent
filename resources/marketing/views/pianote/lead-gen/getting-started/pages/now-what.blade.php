        When you get to G, you head back to A and repeat it all over again.
        <br><br> Those black keys will work as landmarks to help us find these notes. If you find a group of 2 black keys and then look down and to the left, you will find C! Go ahead- find and play all the C’s on your piano. Logically after C, we have D after D we have E, after E we have F, then G then A then B, and we find ourselves back at C.
        <br><br> These little tricks will help you to learn how to make your way around the keyboard as quickly as possible. One of the first things you can practice is finding and saying out loud all the note names on the keyboard!
        <br><br> Now let's come back to C. C is the easiest place to begin learning so we are going to use C as our home base.
        <br><br> Firstly, sit nice and tall at your bench- feet on the floor, back straight, shoulders relaxed. Now, look at your hand. Your fingers are number 1-5 with your thumbs being your 1.
