    <p class="small-body">Welcome back!
        <br><br> In this lesson we are going to learn to play your first real scales. In the previous lesson we learned how to play a 5 finger scale. Now, we are going to look at a complete 8 tone scale.
        <br><br> Scales are important for a variety of reasons. For now, they will help you to become more comfortable moving around the piano and help you to develop the fine motor skills in your hands to be able to play the music you want to play.
        <br><br> So let's begin with C scale. We have 8 notes in total. Now you might be thinking “eight notes?! But I only have 5 fingers” and you are correct! We are going to learn a fancy way of tucking our thumb so that you can play the full scale without any problem. It looks like this:
        <br><br>
    </p>
    <img src="https://d2vyvo0tyx8ig5.cloudfront.net/lead-gen/getting-started/lesson-2-thumb-tuck-1.jpg" alt="thumb-tuck-1">

    <p class="small-body">
        <br>
        As you can see, when I get to the E, I keep my third finger pressed down, and then rotate our thumb UNDER our finger to play the F. Then we reset our hand and finish the scale with our five fingers.
        <br><br> Now that thumb tuck is going to take some practice! So don’t feel discouraged if you don’t get it right away.
        <br><br> Things are a little bit different when we come back DOWN the scale.
        <br><br> We start at the top on C with our 5 finger (remember, the pinky!), then play down the five fingers until we reach the F with our thumb. Then, instead of tucking, we rotate OVER the thumb to land on the E with our 3 finger. I call this a Fly Over!
        <br><br>
    </p>
    <img src="https://d2vyvo0tyx8ig5.cloudfront.net/lead-gen/getting-started/lesson-2-fly-over-1.jpg" alt="fly-over-1">

    <p class="small-body">
        <br>
        Ok! Now it’s time for the left hand! We’ll start with our pinky on the C below the C we were just using.
        <br><br> We begin by playing a five finger scale. When the thumb lands on the G, we do the Fly Over to bring our 3 finger to the A, then finish the scale up to C.
        <br><br>
    </p>
    <img src="https://d2vyvo0tyx8ig5.cloudfront.net/lead-gen/getting-started/lesson-2-fly-over-2.jpg" alt="fly-over-2">

    <p class="small-body">
        <br>
        Now you may have noticed that this is the opposite of our right hand. And that’s true! So on our way down, we will use the thumb tuck technique!
        <br><br>
    </p>
    <img src="https://d2vyvo0tyx8ig5.cloudfront.net/lead-gen/getting-started/lesson-2-thumb-tuck-2.jpg" alt="thumb-tuck-2">

    <p class="small-body">
        <br>
        So when we get to the A we need to tuck our thumb UNDER our 3 finger to land on the G. We then reset our hand and play the five finger scale down to C.
        <br><br> We made it! That’s the C major scale. Now we need to PRACTICE! And I just want to give you a word of encouragement. Playing this scale, especially hands together can be difficult for beginners. So don’t get discouraged if it takes a bit of time! It can take days, sometimes weeks to master this.
        <br><br> The reason it is difficult is because we are changing fingering at different times. But with practice and time, it becomes easier.
        <br><br> So your homework for this lesson is to practice the C major scale. With your right hand, left hand and hands together. Remember to start at a nice easy pace that is comfortable for you.
        <br><br> Have fun, and I’ll see you in the next lesson!
    </p>
